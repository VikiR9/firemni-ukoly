 r:=public.account_gateway('auth-test-only',n2_token,'check','{}');assert (r->>'status')::int=401,'Password reset revokes all';
 r:=public.account_gateway('auth-test-only',n_token,'login','{"username":"NIKOLA","password":"Test-password-123456","ip":"test-old"}');
