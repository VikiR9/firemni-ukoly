 r:=public.account_gateway('auth-test-only',repeat('x',43),'login','{"username":"NIKOLA","password":"Updated-test-password-123","ip":"test-new"}');
 assert r->>'username'='NIKOLA','New password works';
 assert (r->>'must_change_password')::boolean,'Admin reset requires personal password';
