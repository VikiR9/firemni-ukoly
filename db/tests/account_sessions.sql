 r:=public.account_gateway('auth-test-only',n2_token,'check','{}');assert r->>'username'='NIKOLA','Other device still active';
 r:=public.account_gateway('auth-test-only',v_token,'password','{"username":"NIKOLA","password":"Updated-test-password-123"}');
