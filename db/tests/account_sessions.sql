 r:=public.account_gateway('auth-test-only',v_token,'login','{"username":"VIKTOR","password":"Test-password-123456","ip":"test-admin","user_agent":"Test browser"}');
 assert r->>'username'='VIKTOR','Admin login';
 r:=public.account_gateway('auth-test-only',n_token,'login','{"username":"NIKOLA","password":"Test-password-123456","ip":"test-employee"}');
 assert r->>'username'='NIKOLA','Employee login';
 mid:=(r->>'session_id')::uuid;
 r:=public.account_gateway('auth-test-only',n2_token,'login','{"username":"NIKOLA","password":"Test-password-123456","ip":"test-second"}');
 r:=public.account_gateway('auth-test-only',n_token,'list','{}');
 assert not (r->>'can_manage_team')::boolean and jsonb_array_length(r->'people')=1,'Employee sees own account';
 assert not exists(select 1 from jsonb_array_elements(r->'sessions') x where x->>'username'<>'NIKOLA'),'No other devices exposed';
 assert position('token_hash' in r::text)=0 and position('password_hash' in r::text)=0,'Secrets not listed';
 r:=public.account_gateway('auth-test-only',n_token,'password','{"username":"VIKTOR","password":"new-test-pass-123"}');
 assert (r->>'status')::int=403,'No escalation';
 r:=public.account_gateway('auth-test-only',n_token,'revoke_all','{"username":"VIKTOR"}');
